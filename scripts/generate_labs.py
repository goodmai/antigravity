def lab(primary, secondary):
    """Блок «Песочница» с рекомендацией и мультиплатформенными опциями."""
    lines = [
        "## 🧪 Песочница (мультиплатформа)",
        "",
        f"**Рекомендуется для этой лабы:** {LAUNCH[primary].split(' — ')[0]} — {WHY[primary]}.",
        "",
        "Любую задачу можно выполнить в одной из песочниц (быстрый запуск):",
        "",
    ]
    for key in [primary] + [s for s in secondary if s != primary]:
        lines.append(f"- {LAUNCH[key]}")
    lines += [
        "",
        "Полная шпаргалка (bootstrap-скрипт, devcontainer, секреты, выбор платформы): "
        "**[../SANDBOX_SETUP.md](../SANDBOX_SETUP.md)**.",
        "",
        "```bash",
        "# единый вход в любой песочнице",
        "bash scripts/sandbox-bootstrap.sh",
        "```",
        "",
    ]
    return "\n".join(lines)


def task(n, title, goal, steps, accept):
    s = [f"### Задача {n} — {title}", "", f"**Цель:** {goal}", "", "**Шаги:**"]
    s += [f"{i+1}. {st}" for i, st in enumerate(steps)]
    s += ["", f"**Критерий приёмки:** {accept}", ""]
    return "\n".join(s)


