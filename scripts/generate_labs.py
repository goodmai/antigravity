HEADER = """# Лаба {nn}: {title}

> 🔗 Практика к [Уроку {lid}](../../lessons/{lid}/README.md) — *{lt}*

{summary}

## 🎯 Цель

Закрепить материал Урока {lid} через {ntasks} практических задач в облачной
песочнице GitHub. Каждая задача имеет явный **критерий приёмки** — лаба
считается сданной, когда выполнен финальный чек-лист.
"""

FOOTER = """## ✅ Чек-лист сдачи

{checklist}

## 🧭 Связь с курсом

- **Теория:** [Урок {lid}](../../lessons/{lid}/README.md) — *{lt}*
- **Песочницы:** общая шпаргалка [labs/SANDBOX_SETUP.md](../SANDBOX_SETUP.md)
- **Капстоун курса:** [labs/CAPSTONE.md](../CAPSTONE.md) — TeleDrive Ecosystem
- **Навигация:** ← [Лаба {prev}](../{prevp}/README.md) · [Лаба {nxt}](../{nxtp}/README.md) →

---

*Сгенерировано `scripts/generate_labs.py`. Правьте генератор, а не выходные файлы.*
"""


def build(lid, spec):
    nn = f"{lid:02d}"
    tasks_md = []
    for i, (tt, goal, steps, accept) in enumerate(spec["tasks"], 1):
        tasks_md.append(task(i, tt, goal, steps, accept))
    checklist = "\n".join(
        f"- [ ] Задача {i}: {t[0]}" for i, t in enumerate(spec["tasks"], 1)
    )
    prev = f"{(lid-1) if lid > 1 else 30:02d}"
    nxt = f"{(lid+1) if lid < 30 else 1:02d}"
    parts = [
        HEADER.format(nn=nn, title=spec["t"], lid=lid, lt=spec["lt"],
                      summary=spec["sum"], ntasks=len(spec["tasks"])),
        lab(spec["p"], spec["sec"]),
        "## 📋 Задачи\n",
        "\n".join(tasks_md),
        FOOTER.format(lid=lid, lt=spec["lt"], checklist=checklist,
                      prev=prev, prevp=prev, nxt=nxt, nxtp=nxt),
    ]
    return "\n".join(parts).strip() + "\n"


def main():
    root = Path(__file__).resolve().parent.parent
    labs_dir = root / "labs"
    for lid in range(1, 31):
        spec = LABS.get(lid)
        if not spec:
            print(f"!! нет спецификации для урока {lid}")
            continue
        d = labs_dir / f"{lid:02d}"
        d.mkdir(parents=True, exist_ok=True)
        out = d / "README.md"
        out.write_text(build(lid, spec), encoding="utf-8")
        print(f"  labs/{lid:02d}/README.md  ({len(spec['tasks'])} задач)")
    print(f"\nГотово: {len(LABS)} лаб, каждая ≥7 задач.")


if __name__ == "__main__":
    main()
