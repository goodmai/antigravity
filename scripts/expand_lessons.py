def expand_lesson(lesson_num, content):
    """Расширить контент урока дополнительной информацией"""

    # Если есть специальный шаблон для этого урока, добавим его
    expansion = LESSON_EXPANSIONS.get(str(lesson_num), "")

    if expansion:
        # Добавить расширение перед заключением
        content = content + expansion

    # Добавить общие элементы для всех уроков
    if "## Ключевые концепции" not in content:
        content += "\n\n## Ключевые концепции\n\n- Основная тема урока"

    if "## Рекомендуемые источники" not in content:
        content += "\n\n## Рекомендуемые источники\n\n1. Официальная документация Antigravity\n2. Claude Documentation\n3. Relevant research papers"

    return content

def process_lesson_files():
    """Обработать файлы уроков"""
    lessons_dir = Path("lessons")

    # Обработать уроки 1-24
    for lesson_num in range(1, 25):
        lesson_dir = lessons_dir / str(lesson_num)
        readme_path = lesson_dir / "README.md"

        if not readme_path.exists():
            print(f"⚠️  Урок {lesson_num}: README.md не найден")
            continue

        # Прочитать существующий контент
        with open(readme_path, 'r', encoding='utf-8') as f:
            content = f.read()

        # Проверить, нужно ли расширение
        if len(content) < 2000:  # Если контент слишком маленький
            print(f"📝 Расширение урока {lesson_num}...")
            expanded_content = expand_lesson(lesson_num, content)

            # Сохранить расширенный контент
            with open(readme_path, 'w', encoding='utf-8') as f:
                f.write(expanded_content)

            print(f"✅ Урок {lesson_num}: расширен ({len(expanded_content)} символов)")
        else:
            print(f"✓ Урок {lesson_num}: контент достаточный ({len(content)} символов)")

if __name__ == "__main__":
    process_lesson_files()
    print("\n✨ Обработка завершена!")
